function isoAt(minutes: number): string {
  return new Date(BASE_TIME + minutes * 60_000).toISOString();
}

export interface PreviewConventionFixture {
  convention: NewConvention;
  events: NewConventionEvent[];
}

export function buildConPawsPreviewFixture(): PreviewConventionFixture {
  const convention: NewConvention = {
    id: PREVIEW_CONVENTION_ID,
    name: "ConPaws Preview Con",
    startDate: "2026-09-03",
    endDate: "2026-09-06",
    timeZone: "America/New_York",
    icalUrl: null,
    status: "upcoming",
    createdAt: FIXTURE_TIME,
    updatedAt: FIXTURE_TIME,
  };

  const events = SCHEDULE_SHAPE.map(
    ([startMinutes, durationMinutes, roomIndex, audienceIndex], index) => {
      const [topic, category] = TOPICS[index % TOPICS.length];
      const format = FORMATS[Math.floor(index / TOPICS.length)];
      const selected = index === 1 || index % 17 === 0;
      const ordinal = String(index + 1).padStart(3, "0");

      return {
        id: `conpaws-preview-event-${ordinal}`,
        conventionId: PREVIEW_CONVENTION_ID,
        title: `${topic} ${format}`,
        description: `A synthetic ${category.toLowerCase()} session for previewing schedules, filters, conflicts, reminders, and offline behavior.`,
        startTime: isoAt(startMinutes),
        endTime: isoAt(startMinutes + durationMinutes),
        location: "ConPaws Convention Center",
        room: ROOMS[roomIndex],
        category,
        type: AUDIENCES[audienceIndex],
        isInSchedule: selected,
        reminderMinutes: selected ? (index % 34 === 0 ? 60 : 15) : null,
        sourceUid: `conpaws-preview-${ordinal}`,
        sourceUrl: null,
        // Run the label through the real classifier so the fixture exercises
        // the same code path an imported feed does.
        ageRating: ageRatingFromCategory(AUDIENCES[audienceIndex]),
        isAgeRestricted: audienceIndex > 0,
        contentWarning: audienceIndex === 3,
        createdAt: FIXTURE_TIME,
        updatedAt: FIXTURE_TIME,
      } satisfies NewConventionEvent;
    },
  );

  return { convention, events };
}

